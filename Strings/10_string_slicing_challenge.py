'''Q10. String Slicing Challenge

For:
text = "Programming"

Print:
1. Program
2. gram
3. ming
4. Reverse of the string
5. Every second character

Try doing all of them using slicing only.
'''

text = "Programming"

print("1. text[:7] ->", text[:7])
print("2. text[3:7] ->", text[3:7])
print("3. text[7:11] ->", text[7:11])
print("4. text[::-1] ->", text[::-1])
print("5. text[::2] ->", text[::2])
