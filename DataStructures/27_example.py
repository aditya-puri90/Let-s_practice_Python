'''
Q27. Print keys and values

Given:

student = {
    "name": "Aditya",
    "age": 21,
    "course": "BSc Computer Science"
}

Print:

All keys
All values
All key-value pairs

Use:

keys()
values()
items()

'''

student = {
    "name": "Aditya",
    "age": 21,
    "course": "BSc Computer Science"
}

print(student.keys())
print(student.values())
print(student.items())