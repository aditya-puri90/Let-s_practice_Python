'''
Q23. Access dictionary values

Given:

student = {
    "name": "Aditya",
    "age": 21,
    "course": "BSc Computer Science"
}

Print the student's:

Name
Age
Course
'''

student = {
    "name": "Aditya",
    "age": 21,
    "course": "BSc Computer Science"
}


print("Name:",student["name"])
print("Age:",student["age"])
print("Course:",student["course"])